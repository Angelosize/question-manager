def main():
    with open(qfile, "r", encoding="utf-8") as f:
        questions = json.load(f)

    fixed = 0
    for q in questions:
        qid = q["id"]
        if qid not in FIXES:
            continue
        fix = FIXES[qid]
        changes = []
        if "content" in fix and q.get("content") != fix["content"]:
            q["content"] = fix["content"]
            changes.append("题干")
        if "options" in fix and q.get("options") != fix["options"]:
            q["options"] = fix["options"]
            changes.append("选项")
        if changes:
            print(f"🔧 {qid}（第{q.get('content', '')[:12]}...）修正 {'、'.join(changes)}")
            fixed += 1

    with open(qfile, "w", encoding="utf-8") as f:
        json.dump(questions, f, ensure_ascii=False, indent=2)
    print(f"\n✅ 共修正 {fixed} 道题")
    print("⚠️ 请重启后端！")


if __name__ == "__main__":
    main()